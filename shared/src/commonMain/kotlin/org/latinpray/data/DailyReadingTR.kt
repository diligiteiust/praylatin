package org.latinpray.data

fun calculateEaster(year: Int): Pair<Int, Int> {
    val a = year % 19
    val b = year / 100
    val c = year % 100
    val d = b / 4
    val e = b % 4
    val f = (b + 8) / 25
    val g = (b - f + 1) / 3
    val h = (19 * a + b - d - g + 15) % 30
    val i = c / 4
    val k = c % 4
    val l = (32 + 2 * e + 2 * i - h - k) % 7
    val m = (a + 11 * h + 22 * l) / 451
    val n = h + l - 7 * m + 114
    val month = n / 31
    val day = (n % 31) + 1

    return Pair(month, day) // Returns a Pair where first is month (1-12) and second is day
}

